#!/usr/bin/env python3
"""Copies recompiled game functions for the Media Engine.

Usage: scripts/me_copy.py GEN_DIR OUT.c ROOT...

Writes OUT.c with every function the ROOTs call, directly or through others,
taken from the recompiler's output in GEN_DIR and renamed me_<name>, so that
the ME runs its own copies (runtime/src/audio/synth.c). What the copies reach
outside the game's own code is redirected to the ME's stand-ins: indirect
calls to me_lookup_func, do_break and switch_error to me_do_break and
me_switch_error (recomp_psp.h gives the copies their own FPU rounding mode
too). Anything else outside is an error: the ME cannot run
the main CPU's runtime.
"""
import glob
import os
import re
import sys

FUNC = re.compile(r"^RECOMP_FUNC void (\w+)\(uint8_t\* rdram, recomp_context\* RECOMP_RESTRICT ctx\) \{.*?^;?\}", re.S | re.M)
CALL = re.compile(r"\b(\w+)\(rdram, ctx\)")
# What generated code may use without leaving the copy: recomp_psp.h's macros and inline helpers.
HELPERS = re.compile(r"\b(get_cop1_cs|set_cop1_cs|do_cvt_w_s|do_cvt_w_d|load_doubleword)\b")
OUTSIDE = {"LOOKUP_FUNC": "me_lookup_func", "do_break": "me_do_break", "switch_error": "me_switch_error"}


def main():
    gen, out, roots = sys.argv[1], sys.argv[2], sys.argv[3:]
    bodies = {}
    for path in sorted(glob.glob(os.path.join(gen, "funcs_*.c"))):
        for m in FUNC.finditer(open(path).read()):
            bodies[m.group(1)] = m.group(0)

    copied, todo = [], list(roots)
    while todo:
        name = todo.pop(0)
        if name in copied:
            continue
        if name not in bodies:
            sys.exit(f"me_copy: {name} is not in {gen} (a runtime function the ME cannot call)")
        copied.append(name)
        todo += [c for c in CALL.findall(bodies[name]) if c not in copied]

    # Every other call in the copies must be one of the redirected ones.
    known = set(bodies) | set(OUTSIDE)
    for name in copied:
        body = HELPERS.sub("", bodies[name])
        for callee in re.findall(r"\b([A-Za-z_]\w*_recomp|func_\w+|do_\w+|\w+_error)\(", body):
            if callee not in known:
                sys.exit(f"me_copy: {name} calls {callee}, which the ME cannot run")

    with open(out, "w") as f:
        f.write("/* Generated by scripts/me_copy.py: game functions for the Media Engine. */\n")
        f.write("#define RT_ME_COPY\n#include \"recomp_psp.h\"\n\n")
        f.write("recomp_func_t* me_lookup_func(int32_t vram);\n")
        f.write("void me_do_break(uint32_t vram);\n")
        f.write("void me_switch_error(const char* func, uint32_t vram, uint32_t jtbl);\n")
        for old, new in OUTSIDE.items():
            f.write(f"#undef {old}\n#define {old} {new}\n")
        for name in copied:
            f.write(f"#define {name} me_{name}\n")
        for name in copied:
            f.write(f"RECOMP_FUNC void {name}(uint8_t* rdram, recomp_context* RECOMP_RESTRICT ctx);\n")
        f.write("\n")
        for name in copied:
            f.write(bodies[name] + "\n\n")
    print(f"me_copy: {len(copied)} functions -> {out}")


if __name__ == "__main__":
    main()
